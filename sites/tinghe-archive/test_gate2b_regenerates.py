#!/usr/bin/env python3
"""Pin the Gate 2b ordering rule that made content days fail to ship.

The bug (measured 2026-10-14, -15 and -16): Gate 2b checked search-index.json
with `--check-only` BEFORE Gate 4 rewrote desk.json. Every run that authored an
episode therefore found its own index one entry stale, `build_site_meta` exited
1, and the pipeline returned before the deploy. The receipt then said
BUILD_FAILED for a day that had produced content, and every reader of receipts
believed it.

Three receipts agree with the diagnosis:
  2026-10-14  BUILD_FAILED  delivered=5   full
  2026-10-15  BUILD_FAILED  delivered=1   catchup
  2026-10-16  BUILD_FAILED  delivered=1   full
...while the no-write runs of the same days all passed, because they never wrote
a new episode into desk.json.

This test asserts the rule rather than the incident: derived site projections are
REGENERATED by the gate, and only real validators may run in check-only mode.
"""
from __future__ import annotations

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = (HERE / "daily_originals.py").read_text(encoding="utf-8")

failures: list[str] = []


def check(name: str, cond: bool, detail: str = "") -> None:
    print(f"[{'PASS' if cond else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""))
    if not cond:
        failures.append(name)


# --- the gate table itself ---------------------------------------------------

m = re.search(r"gates\s*=\s*\((.*?)\)\n", SRC, re.S)
check("the Gate 2b table is present and parseable", bool(m))
if m:
    body = m.group(1)
    entries = dict(re.findall(r'\("(\w+)",\s*\w+,\s*(True|False)\)', body))
    check("build_site_meta is listed", "build_site_meta" in entries,
          f"found: {sorted(entries)}")
    check("build_site_meta regenerates rather than checks",
          entries.get("build_site_meta") == "False",
          "check-only means the gate fails on its own output's staleness")
    check("build_chapter_pages regenerates too",
          entries.get("build_chapter_pages") == "False",
          "it writes derived pages; checking them was the same trap")
    check("check_site_integrity still fails closed",
          entries.get("check_site_integrity") == "False" or
          "check_site_integrity" in entries,
          "it validates the published tree and must stay a real check")


# --- the causal claim, verified against the tool itself ----------------------
#
# Adding an episode to desk.json must NOT make build_site_meta fail when run as
# the gate now runs it. This is the reproduction that proved the bug, inverted.

import json  # noqa: E402
import subprocess  # noqa: E402

DESK = HERE / "public" / "data" / "originals" / "desk.json"
IDX = HERE / "public" / "data" / "search-index.json"

if DESK.is_file() and IDX.is_file():
    desk_before = DESK.read_bytes()
    idx_before = IDX.read_bytes()
    try:
        d = json.loads(desk_before.decode("utf-8"))
        for w in d.get("works", []):
            if w.get("episodes"):
                w["episodes"].append(dict(w["episodes"][-1], id="epGATE2B"))
                break
        DESK.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")

        regen = subprocess.run([sys.executable, "build_site_meta.py"],
                               cwd=HERE, capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=300)
        check("a newly published episode does not fail the gate",
              regen.returncode == 0,
              f"exit={regen.returncode}: {regen.stdout.strip()[-200:]}")

        after = subprocess.run([sys.executable, "build_site_meta.py", "--check-only"],
                               cwd=HERE, capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=300)
        check("regenerating leaves the index consistent",
              after.returncode == 0,
              "the next run must not find drift the last run created")
    finally:
        DESK.write_bytes(desk_before)
        IDX.write_bytes(idx_before)
else:
    check("desk.json and search-index.json exist to test against",
          False, f"missing under {HERE / 'public' / 'data'}")

print()
if failures:
    print(f"FAILED {len(failures)} check(s):")
    for f in failures:
        print(f"  - {f}")
    sys.exit(1)
print("RESULT: the site projections are regenerated, so authoring cannot fail the gate")
