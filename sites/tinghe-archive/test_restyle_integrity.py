#!/usr/bin/env python3
"""Check the restyle did not break the pages that share app.css.

The 2026-10-12 visual pass rewrote :root and .top in the one stylesheet every
page loads — including the 248 static chapter snapshots in public/read/, which
are generated by build_chapter_pages.py and are the links people share. A
restyle that passes on the SPA home page but breaks a chapter snapshot is still
a broken release, and nothing in the pipeline renders a chapter page.

This checks, without a browser: every generated page still references the
current stylesheet version, the markup classes the new rules target all exist
somewhere in the generated pages, and no page lost its <title>.
"""
from __future__ import annotations

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
PUBLIC = HERE / "public"
READ = PUBLIC / "read"

failures: list[str] = []


def check(name: str, cond: bool, detail: str = ""):
    print(f"[{'PASS' if cond else 'FAIL'}] {name}" + (f"  {detail}" if detail else ""))
    if not cond:
        failures.append(name)


pages = sorted(READ.glob("c*.html"))
check("chapter pages exist", len(pages) > 0, f"{len(pages)} pages")

sys.path.insert(0, str(HERE))
from build_chapter_pages import CSS_V  # noqa: E402

stale = [p.name for p in pages if f"app.css?v={CSS_V}" not in p.read_text(encoding="utf-8")]
check("every chapter page loads the current stylesheet", not stale,
      f"stale: {stale[:3]}" if stale else "")

no_title = [p.name for p in pages if "<title>" not in p.read_text(encoding="utf-8")]
check("every chapter page kept a <title>", not no_title)

# The new rules restyle these class names. If a generator stopped emitting one,
# the rule is dead code and the page silently keeps the old look.
sample = pages[0].read_text(encoding="utf-8")
for cls in ("reader-shell", "pager", "static-foot", "reader", "chapter-kicker"):
    check(f"class '{cls}' still present in generated pages", cls in sample)

index = (READ / "index.html")
check("read/index.html exists", index.is_file())
if index.is_file():
    check("read/index.html loads the current stylesheet",
          f"app.css?v={CSS_V}" in index.read_text(encoding="utf-8"))

# app.css must actually define the tokens the restyle introduced.
css = (PUBLIC / "assets" / "app.css").read_text(encoding="utf-8")
for token in ("--r-lg", "--glow-lift", "--glass", "cover-float", "btn-sheen"):
    check(f"token/anim '{token}' defined in app.css", token in css)

# Brace balance is the cheapest real syntax gate there is.
check("app.css braces balanced", css.count("{") == css.count("}"),
      f"{css.count('{')} open vs {css.count('}')} close")

print()
print(f"chapter pages checked: {len(pages)}")
if failures:
    print(f"FAILED {len(failures)} check(s)")
    sys.exit(1)
print("RESULT: restyle intact across the SPA and every generated snapshot")
