FIX = {
  "fanguan": [("鞋 single 不了", "鞋落单不了")],
  "liufang": [("拿bone里剩下那半截换", "拿骨头里剩下那半截换"), ("明儿拿bone里剩下那半截", "明儿拿骨头里剩下那半截")],
}

def main():
    for wid, blocks in NEW.items():
        p = SRC / wid / "work.json"
        d = json.loads(p.read_text(encoding="utf-8"))
        for e in d["episodes"]:
            if e.get("no") == 15:
                e["blocks"] = blocks
        p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
        n = sum(len(b.get("t", "")) for b in blocks)
        print("rewrote", wid, "blocks=", len(blocks), "chars=", n)
    for wid, pairs in FIX.items():
        p = SRC / wid / "work.json"
        t = p.read_text(encoding="utf-8")
        for a, b in pairs:
            assert a in t, (wid, a)
            t = t.replace(a, b)
        p.write_text(t, encoding="utf-8")
        print("fixed", wid)

if __name__ == "__main__":
    main()
