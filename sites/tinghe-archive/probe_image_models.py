"""Probe which image models actually answer right now. Do not assume.

The user listed eight image models as available: gpt-image-2,
gpt-image-2.5-flare, gpt-image-2.5-sunburst, grok-imagine-image,
grok-imagine-image-quality, agnes-image-2.5-flash, agnes-image-2.1-flash and
agnes-image-2.0-flash. Earlier today gpt-image-2 returned 502 and grok returned
503 from the same gateway, four retries apart — so "configured" and "working"
have already come apart once today.

Each model is sent one real, minimal generation request. A probe that only
checks the endpoint would have passed while both routes were down.

Cheapest possible image: 256x256, low quality, one image. This is a liveness
check, not the cover — the covers are generated by build_entry_covers.py once a
route is known to work.

The response shape differs by provider (base64 vs a temporary URL), so success is
"an image came back", not a specific field.

Writes research/image_model_liveness.json. No key value is recorded.
"""
from __future__ import annotations

import base64
import json
import os
import pathlib
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "research" / "image_model_liveness.json"
SHENWEN = os.environ.get("SHENWEN_IMAGE_BASE_URL", "https://api.shenwenai.com/v1").rstrip("/")

CANDIDATES = [
    # (model, key env var, base url)
    ("gpt-image-2",                 "SHENWEN_IMAGE_API_KEY", SHENWEN),
    ("gpt-image-2.5-flare",         "SHENWEN_IMAGE_API_KEY", SHENWEN),
    ("gpt-image-2.5-sunburst",      "SHENWEN_IMAGE_API_KEY", SHENWEN),
    ("grok-imagine-image",          "SHENWEN_GROK_API_KEY",  SHENWEN),
    ("grok-imagine-image-quality",  "SHENWEN_GROK_API_KEY",  SHENWEN),
    ("agnes-image-2.5-flash",       "AGNES_API_KEY",         SHENWEN),
    ("agnes-image-2.1-flash",       "AGNES_API_KEY",         SHENWEN),
    ("agnes-image-2.0-flash",       "AGNES_API_KEY",         SHENWEN),
]

PROMPT = "a single pale moon above black water, no text"


def probe(model: str, key: str, base: str, tmp: pathlib.Path) -> dict:
    rec = {"model": model, "base_url": base, "credential_source": key}
    if not os.environ.get(key):
        rec.update(status="NO_CREDENTIAL")
        return rec

    payload = {"model": model, "prompt": PROMPT, "n": 1}
    if model.startswith("gpt-image"):
        payload.update(size="256x256", quality="low")
    else:
        payload.update(response_format="url")

    req = urllib.request.Request(
        f"{base}/images/generations",
        data=json.dumps(payload).encode("utf-8"), method="POST",
        headers={"Authorization": f"Bearer {os.environ[key]}",
                 "Content-Type": "application/json"})

    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=180) as resp:
            body = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        detail = ""
        try:
            detail = e.read().decode("utf-8", "replace")[:200]
        except Exception:                                       # noqa: BLE001
            pass
        rec.update(status="HTTP_ERROR", http_status=e.code,
                   detail=detail or e.reason)
        return rec
    except Exception as e:                                      # noqa: BLE001
        rec.update(status="ERROR", detail=f"{type(e).__name__}: {e}"[:180])
        return rec

    item = (body.get("data") or [{}])[0]
    url, b64 = item.get("url"), item.get("b64_json")
    if not url and not b64:
        rec.update(status="NO_IMAGE", detail=json.dumps(body)[:200])
        return rec

    # Prove the bytes actually arrive; a URL that 403s is not a working route.
    try:
        if url:
            with urllib.request.urlopen(url, timeout=120) as r:
                data = r.read()
        else:
            data = base64.b64decode(b64)
        tmp.write_bytes(data)
        rec.update(status="PASS", bytes=len(data), seconds=round(time.time() - t0, 1),
                   detail=f"{data[:8].hex()}")
    except Exception as e:                                      # noqa: BLE001
        rec.update(status="IMAGE_FETCH_FAILED",
                   detail=f"{type(e).__name__}: {e}"[:180])

    if not url:
        rec["response"] = "b64_json"
    else:
        rec["response"] = "temporary_image_url"
    return rec


def main() -> int:
    tmp = HERE / "research" / "_liveness_probe.bin"
    tmp.parent.mkdir(parents=True, exist_ok=True)
    print(f"{'model':<30}{'status':<20}{'s':>6}  detail")
    print("-" * 88)
    results = []
    for model, key, base in CANDIDATES:
        rec = probe(model, key, base, tmp)
        results.append(rec)
        print(f"{model:<30}{rec['status']:<20}"
              f"{str(rec.get('seconds', '-')):>6}  "
              f"{str(rec.get('detail', ''))[:44]}")
    tmp.unlink(missing_ok=True)

    working = [r["model"] for r in results if r["status"] == "PASS"]
    OUT.write_text(json.dumps({
        "schema": "ace.image.model_liveness.v1",
        "checked_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "probe": "one real 256x256 generation per model; PASS means bytes arrived",
        "results": results,
        "working": working,
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    print()
    print(f"可用: {working or '无'}")
    print(f"receipt: {OUT.relative_to(HERE)}")
    return 0 if working else 1


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
